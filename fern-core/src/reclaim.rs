//! 把用完的内存真正还给系统。
//!
//! 「释放了」和「还回去了」是两件事。实测（Linux/glibc，release 构建）：
//!
//! ```text
//! 补全 3946 个文件 / 911 MB     峰值 60.4 MB
//! 丢掉所有引用、静置 20 秒       60.4 MB   ← 一个字节都没还
//! malloc_trim(0)                33.1 MB
//! ```
//!
//! 那 27 MB 没有泄漏——它是 free 过的，只是 glibc 攥在自己的 arena 里等下一次
//! 分配。启动器自己接着跑当然无所谓，可**紧接着起来的是一个要吃几个 G 的
//! JVM**，这时候攥着就是纯粹的浪费。起停游戏一轮同样留下约 6 MB。
//!
//! 只做 Linux。macOS 和 Windows 的分配器我们没有量过，而按一条没量过的猜想去
//! 调另外两个平台的内存行为，不比不调更好。

/// 把分配器手里的空闲内存交回系统。
///
/// 挑时机而不是定期跑：这一趟要走一遍空闲链表，几毫秒，不该出现在热路径上。
/// 只在「一件占内存的事刚做完，而下一件事更需要内存」的那两个点调用。
pub fn give_back() {
    #[cfg(target_env = "gnu")]
    {
        // SAFETY: malloc_trim 不接触我们的任何指针，只把 arena 里空闲的页还给
        // 内核。参数 0 表示不给自己留任何余量。
        unsafe {
            libc::malloc_trim(0);
        }
    }
}
